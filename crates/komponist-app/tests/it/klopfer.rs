//! Flow 3 with klopfer (HANDOFF §9 "Drum-Beat mit klopfer im Step Sequencer bauen und abspielen";
//! PLAN WP-54).
//!
//! 1. **Build** (kittest, always runs): a klopfer track; a double-click into its empty lane makes a
//!    step clip whose rows klopfer decides (pads 1–8 = notes 36–43, without note names) and opens
//!    it; the row headers show the pads "P1" …; clicks on steps build the beat.
//! 2. **Play** (needs the klopfer bundle and klopfer's test kit, skips without them): the project,
//!    with the test kit as klopfer's state, renders offline through the bridge with the engine's
//!    export pipeline (WP-53a) into a float WAV. Every set step starts a hit exactly at its step
//!    position, and the hit is the sample of the expected pad (normalised cross-correlation
//!    against the kit's sample files); steps that are off start nothing.
//!
//! The bundle comes from the app's own lookup (`PluginManagerConfig::defaults`: installed, then
//! `../klopfer/target/bundled/Klopfer.clap` from `scripts/build-klopfer.sh`, then
//! `~/.clap/Klopfer.clap`); the test kit is `../klopfer/testkit-out/Testkit.klopfer`, generated by
//! klopfer's `tools/testkit`.

