// 2. Play it: offline render through the bridge

/// klopfer's test kit, or `None` with a note.
fn testkit() -> Option<PathBuf> {
    let kit =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../klopfer/testkit-out/Testkit.klopfer");
    match kit.canonicalize() {
        Ok(kit) => Some(kit),
        Err(_) => {
            eprintln!(
                "skipped: {} is missing (klopfer's tools/testkit)",
                kit.display()
            );
            None
        }
    }
}

/// Device latencies from the plugin manager, as the app's `EngineSync` passes them.
struct Env<'a>(&'a PluginManager);

impl CompileEnv for Env<'_> {
    fn midi_port(&self, _device_name: &str) -> Option<MidiPort> {
        None
    }

    fn device_latency(&self, device: DeviceId) -> u32 {
        self.0.latency(device)
    }
}

/// Renders `project` from tick 0 for one bar plus `tail_ms` at [`RATE`] through the export
/// pipeline; returns the mono mix (L + R) / 2 and the frame of each 1/16 step.
fn render(project: &Project, klopfer: PathBuf, tail_ms: u64) -> (Vec<f32>, Vec<usize>) {
    let dir = scratch("klopfer-flow3");
    let mut manager = PluginManager::new(PluginManagerConfig {
        bridge_exe: bridge_exe(),
        cache_file: dir.join("cache/plugins.json"),
        klopfer_bundle: Some(klopfer),
        parallel_scans: 1,
    });
    let setup = ProcessorSetup {
        sample_rate: RATE as f32,
        max_block: komponist_engine::MAX_BLOCK,
    };
    let (mut engine, mut handle) = Engine::new(EngineConfig {
        sample_rate: RATE as f32,
        max_block: komponist_engine::MAX_BLOCK,
        seed: 1,
    });
    let program = compile::build(project, None, &Env(&manager));
    let device = project.tracks[0].channel.devices[0].clone();
    for (id, slot) in compile::slot_changes(None, &program).added {
        assert_eq!(id, device.id);
        let processor = manager.create_processor(&device, setup).expect("bridge");
        handle
            .send(Command::InsertProcessor { slot, processor })
            .expect("command queue");
    }
    handle
        .send(Command::SetProgram(Box::new(program.clone())))
        .expect("command queue");
    manager.set_render_mode(RenderMode::Offline);

    // The export waits until every device is `Ok` (WP-53a).
    let mut run = |engine: &mut Engine, manager: &mut PluginManager| {
        engine.render(BLOCK);
        while handle.poll().is_some() {}
        manager.poll();
    };
    let deadline = Instant::now() + PATIENCE;
    while manager.status(device.id) != DeviceStatus::Ok {
        assert!(Instant::now() < deadline, "klopfer did not load");
        run(&mut engine, &mut manager);
        std::thread::sleep(Duration::from_millis(2));
    }
    // klopfer reports active before its pads sound (it prepares the kit in the background); the
    // device stays `Loading` for `komponist_plugins::WARM_UP` after that, so `Ok` means ready.
    assert_eq!(
        manager.state_warning(device.id),
        None,
        "the kit state loads"
    );

    let map = &program.tempo_map;
    let job = ExportJob {
        path: dir.join("flow3.wav"),
        sample_rate: RATE,
        range: ExportJob::frames_of(map, TickRange::new(Tick::ZERO, Tick(BAR)), RATE),
        tail: ExportJob::tail_frames(tail_ms as f32 / 1000.0, RATE),
        bit_depth: BitDepth::Float32,
        normalize: None,
        dither: false,
    };
    let t0 = Instant::now();
    let report = export(
        &mut engine,
        &mut handle,
        &program,
        &job,
        &AtomicBool::new(false),
        |_| {},
    )
    .expect("export");
    eprintln!(
        "rendered {} frames, peak {:.1} dBFS",
        report.frames, report.peak_db
    );
    eprintln!(
        "DEBUG export took {:?}, late blocks {}",
        t0.elapsed(),
        manager.late_blocks(device.id)
    );
    while let Some(e) = handle.poll() {
        eprintln!("DEBUG engine event {e:?}");
    }
    for e in manager.poll() {
        eprintln!("DEBUG manager event {e:?}");
    }
    manager.shutdown();

    let mut wav = hound::WavReader::open(&job.path).expect("wav");
    assert_eq!(wav.spec().sample_rate, RATE);
    assert_eq!(wav.spec().channels, 2);
    let samples: Vec<f32> = wav.samples::<f32>().map(Result::unwrap).collect();
    let mono: Vec<f32> = samples.chunks(2).map(|f| (f[0] + f[1]) / 2.0).collect();
    let steps = (0..16)
        .map(|s| {
            let ticks = TickRange::new(Tick::ZERO, Tick(s * STEP));
            ExportJob::frames_of(map, ticks, RATE).end as usize
        })
        .collect();
    let _ = std::fs::remove_dir_all(&dir);
    (mono, steps)
}

/// A test kit sample as f32 (16-bit mono).
fn sample(kit: &Path, name: &str) -> Vec<f32> {
    let path = kit.parent().unwrap().join("samples").join(name);
    let mut wav = hound::WavReader::open(&path).expect("test kit sample");
    assert_eq!((wav.spec().channels, wav.spec().sample_rate), (1, RATE));
    wav.samples::<i16>()
        .map(|s| f32::from(s.unwrap()) / 32768.0)
        .collect()
}

/// Frames compared after an onset (23 ms: the attack of the new hit dominates older tails).
const WINDOW: usize = 1024;
/// Onsets searched this many frames around the step position.
const LAGS: i64 = 32;

/// The best normalised cross-correlation of `audio` from `at + lag` with the start of `sample`,
/// over `−LAGS ..= LAGS`: `(correlation, lag)`.
fn correlate(audio: &[f32], at: usize, sample: &[f32]) -> (f32, i64) {
    let n = WINDOW.min(sample.len());
    let y = &sample[..n];
    let yy: f32 = y.iter().map(|v| v * v).sum();
    (-LAGS..=LAGS)
        .filter_map(|lag| {
            let start = usize::try_from(at as i64 + lag).ok()?;
            let x = audio.get(start..start + n)?;
            let xy: f32 = x.iter().zip(y).map(|(a, b)| a * b).sum();
            let xx: f32 = x.iter().map(|v| v * v).sum();
            (xx > 0.0).then(|| (xy / (xx * yy).sqrt(), lag))
        })
        .max_by(|a, b| a.0.total_cmp(&b.0))
        .unwrap_or((0.0, 0))
}

fn rms(audio: &[f32]) -> f32 {
    (audio.iter().map(|v| v * v).sum::<f32>() / audio.len().max(1) as f32).sqrt()
}

#[test]
fn flow_3_plays_the_expected_pads_in_an_offline_render() {
    let Some(klopfer) = PluginManagerConfig::defaults().klopfer_bundle else {
        eprintln!("skipped: Klopfer.clap not found (scripts/build-klopfer.sh)");
        return;
    };
    let Some(kit) = testkit() else {
        return;
    };
    eprintln!("klopfer: {}; kit: {}", klopfer.display(), kit.display());
    let (mut project, _) = build_beat();
    // The kit, as klopfer's state (what loading it in klopfer's own GUI leaves in the document).
    let state = klopfer_kit_state(&kit).expect("kit state");
    let track = Arc::make_mut(&mut project.tracks[0]);
    Arc::make_mut(&mut track.channel.devices[0]).state = Some(Arc::from(state));

    let (audio, steps) = render(&project, klopfer, 500);
    let candidates: Vec<(usize, &str, Vec<f32>)> = PAD_SAMPLES
        .iter()
        .enumerate()
        .flat_map(|(pad, names)| names.iter().map(move |n| (pad, *n)))
        .map(|(pad, name)| (pad, name, sample(&kit, name)))
        .collect();

    let first = audio.iter().position(|v| v.abs() > 1e-4);
    eprintln!("DEBUG first sound at {first:?}, len {}", audio.len());
    for (i, chunk) in audio.chunks(2756).enumerate().take(40) {
        let pk = chunk.iter().fold(0.0f32, |m, v| m.max(v.abs()));
        eprintln!("DEBUG half-step {i}: peak {pk:.3}");
    }
    eprintln!("step  frame  expected         best match       corr   lag  peak");
    for (step, &frame) in steps.iter().enumerate() {
        let end = steps.get(step + 1).copied().unwrap_or(frame + steps[1]);
        let peak = audio[frame..end].iter().fold(0.0f32, |m, v| m.max(v.abs()));
        let hit = BEAT.iter().find(|&&(_, s)| s == step).map(|&(row, _)| row);
        let Some(pad) = hit else {
            // An off step starts nothing: the level only decays across it.
            let before = rms(&audio[frame - WINDOW..frame]);
            let after = rms(&audio[frame..frame + WINDOW]);
            eprintln!(
                "{:>4}  {frame:>5}  —                                            {peak:.3}",
                step + 1
            );
            assert!(
                after <= before * 1.25 + 1e-4,
                "step {}: a new sound starts ({before:.4} → {after:.4})",
                step + 1
            );
            continue;
        };
        let (best_pad, best_name, (corr, lag)) = candidates
            .iter()
            .map(|(pad, name, s)| (*pad, *name, correlate(&audio, frame, s)))
            .max_by(|a, b| a.2.0.total_cmp(&b.2.0))
            .unwrap();
        eprintln!(
            "{:>4}  {frame:>5}  P{} {:<14} {best_name:<16} {corr:.3}  {lag:>3}  {peak:.3}",
            step + 1,
            pad + 1,
            PAD_SAMPLES[pad][0],
        );
        assert_eq!(
            best_pad,
            pad,
            "step {}: expected pad {}, heard {best_name} ({corr:.3})",
            step + 1,
            pad + 1
        );
        assert!(
            corr > 0.6,
            "step {}: {best_name} only matches {corr:.3}",
            step + 1
        );
        assert!(
            lag.abs() <= 2,
            "step {}: the hit starts {lag} frames off its step",
            step + 1
        );
        if (pad, step) == (SOFT_KICK.0, SOFT_KICK.1) {
            assert_eq!(best_name, "kick-soft.wav", "velocity {}", SOFT_KICK.2);
        } else if pad == 0 {
            assert_eq!(best_name, "kick.wav", "velocity 100");
        }
    }
}
