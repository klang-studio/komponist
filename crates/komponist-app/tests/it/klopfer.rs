const BAR: i64 = 3840;
/// Ticks per 1/16 step.
const STEP: i64 = 240;

/// The beat: `(row, step)` per hit, all at the default velocity 100 except the second kick.
/// Rows are klopfer's pads 1–8; with the test kit: 1 Kick, 2 Snare, 3 Clap, 4 Rim, 5 Hat Closed,
/// 6 Hat Open, 7 Shaker, 8 Crash.
const BEAT: [(usize, usize); 10] = [
    (0, 0),
    (4, 2),
    (1, 4),
    (4, 6),
    (3, 7),
    (0, 8),
    (4, 10),
    (6, 11),
    (1, 12),
    (2, 14),
];
/// The second kick (step 9) is soft: klopfer's pad 1 has a velocity layer below 91.
const SOFT_KICK: (usize, usize, u8) = (0, 8, 80);

/// The sample files each pad of the test kit plays (`Testkit.klopfer`), pads 1–8.
const PAD_SAMPLES: [&[&str]; 8] = [
    &["kick.wav", "kick-soft.wav"],
    &["snare-1.wav", "snare-2.wav", "snare-3.wav"],
    &["clap.wav"],
    &["rim.wav"],
    &["hat-closed.wav"],
    &["hat-open.wav"],
    &["shaker.wav"],
    &["crash.wav"],
];

/// The test kit's sample rate (44.1 kHz, mono, 16 bit); the render runs at it, so klopfer plays
/// the samples without resampling and the onsets compare 1:1.
const RATE: u32 = 44_100;
/// Frames per engine call before the export.
const BLOCK: usize = 256;

// ------------------------------------------------------------------------------------------------
// 1. Build the beat in the UI

fn klopfer_ref() -> PluginRef {
    PluginRef {
        format: PluginFormat::Builtin,
        id: BUILTIN_KLOPFER.into(),
        name: "klopfer".into(),
        vendor: "Klopfer".into(),
        version: "0.1.0".into(),
        module: Box::default(),
    }
}

/// An empty project with one klopfer track ("Drums", as a drop from the browser makes it).
fn drums_project() -> Project {
    let spec = NewTrack {
        name: None,
        hue: None,
        instrument: Some(klopfer_ref()),
        index: None,
        arm_exclusive: false,
    };
    let (p, _) = edits::add_track(&Project::new(DEFAULT_PROJECT_NAME), spec).unwrap();
    p
}

fn harness(app: App) -> Harness<'static, App> {
    let mut h = komponist_ui::snapshot::builder::<App>(1.0)
        .with_size(vec2(1920.0, 1080.0))
        .with_max_steps(64)
        .with_step_dt(1.0 / 60.0)
        .build_ui_state(|ui, app: &mut App| app.show(ui), app);
    h.run_steps(2);
    h
}

fn button(h: &Harness<'_, App>, pos: Pos2, pressed: bool) {
    h.event(Event::PointerButton {
        pos,
        button: PointerButton::Primary,
        pressed,
        modifiers: Modifiers::NONE,
    });
}

/// A click at `pos` (press and release in one frame, as kittest and egui-mcp click), after half
/// a second without input so that it is no double-click.
fn click_at(h: &mut Harness<'_, App>, pos: Pos2) {
    h.run_steps(30);
    h.event(Event::PointerMoved(pos));
    h.step();
    button(h, pos, true);
    button(h, pos, false);
    h.run_steps(2);
}

fn double_click(h: &mut Harness<'_, App>, pos: Pos2) {
    h.run_steps(30);
    h.event(Event::PointerMoved(pos));
    h.step();
    for _ in 0..2 {
        button(h, pos, true);
        button(h, pos, false);
        h.step();
    }
    h.run_steps(2);
}

/// The arrangement's x of `tick` (from its ruler).
fn x_of(h: &Harness<'_, App>, tick: Tick) -> f32 {
    let ruler = h
        .get_all_by_role_and_label(Role::Slider, arrangement_names::RULER)
        .map(|n| n.rect())
        .min_by(|a, b| a.top().total_cmp(&b.top()))
        .expect("ruler");
    let v = h.state().ui().arrangement;
    ruler.left() + ((tick.0 as f64 - v.scroll_tick) as f32) * (v.px_per_bar / BAR as f32)
}

fn pattern(app: &App, clip: ClipId) -> StepClip {
    match &app.project().find_clip(clip).expect("clip").1.content {
        ClipContent::Step(s) => s.clone(),
        ClipContent::Midi(_) => panic!("not a step clip"),
    }
}

/// Flow 3 up to the finished beat, through the UI. Returns the project and the clip.
fn build_beat() -> (Project, ClipId) {
    let mut h = harness(App::headless(drums_project()));
    // A double-click into the empty lane of Drums in bar 1: a one-bar step clip, opened. (The
    // headless app's built-in host has no klopfer bundle, so the header says it is missing.)
    let header = h
        .get_by_role_and_label(Role::Row, "Spur Drums, Plugin fehlt: klopfer")
        .rect();
    let at = pos2(x_of(&h, Tick(BAR / 3)), header.center().y);
    double_click(&mut h, at);
    let track = &h.state().project().tracks[0];
    assert_eq!(track.clips.len(), 1, "a double-click makes one clip");
    let clip = track.clips[0].id;
    assert_eq!(h.state().ui().editor.clip, Some(clip));
    assert_eq!(
        (track.clips[0].start, track.clips[0].length),
        (Tick::ZERO, Tick(BAR))
    );

    // klopfer decided the rows: pads 1–8, named like S03's rows, labelled "P1" … in the headers.
    let rows = pattern(h.state(), clip).rows;
    let notes: Vec<u8> = rows.iter().map(|r| r.note).collect();
    assert_eq!(notes, (36..44).collect::<Vec<u8>>());
    let instrument = Some(klopfer_ref());
    let labels: Vec<String> = rows
        .iter()
        .map(|r| step_rows::row_label(instrument.as_ref(), r.note))
        .collect();
    assert_eq!(labels, ["P1", "P2", "P3", "P4", "P5", "P6", "P7", "P8"]);
    for row in &rows {
        h.get_by_role_and_label(Role::Button, &format!("Zeile {}", row.name));
    }

    // The beat, one click per step.
    for (row, step) in BEAT {
        let label = format!("Step {}, {}, ", step + 1, rows[row].name);
        let pos = h.get_by_label_contains(&label).rect().center();
        click_at(&mut h, pos);
        assert!(
            pattern(h.state(), clip).rows[row].steps[step].on,
            "step {} of {} is on",
            step + 1,
            rows[row].name
        );
    }
    // The vertical drag on a step sends this (S03 "Ziehen ↕ = Velocity").
    let (row, step, velocity) = SOFT_KICK;
    h.state_mut().dispatch(Action::Edit(EditAction::SetStep {
        clip,
        row,
        step,
        prop: StepProp::Velocity(velocity),
    }));
    h.run_steps(2);
    let on: usize = pattern(h.state(), clip)
        .rows
        .iter()
        .map(|r| r.steps.iter().filter(|s| s.on).count())
        .sum();
    assert_eq!(on, BEAT.len());
    (Project::clone(h.state().project()), clip)
}

#[test]
fn flow_3_builds_a_beat_on_klopfers_pads() {
    let (project, clip) = build_beat();
    let ClipContent::Step(steps) = &project.find_clip(clip).unwrap().1.content else {
        panic!("step clip");
    };
    // What the engine will play: one note per set step, at the step, on the row's pad.
    let hits = steps.hits(Tick(BAR));
    let mut played: Vec<(i64, u8, u8)> = hits
        .iter()
        .map(|h| (h.start.0, h.note, h.velocity))
        .collect();
    played.sort_unstable();
    let mut expected: Vec<(i64, u8, u8)> = BEAT
        .iter()
        .map(|&(row, step)| {
            let velocity = if (row, step) == (SOFT_KICK.0, SOFT_KICK.1) {
                SOFT_KICK.2
            } else {
                100
            };
            (step as i64 * STEP, 36 + row as u8, velocity)
        })
        .collect();
    expected.sort_unstable();
    assert_eq!(played, expected);
}

